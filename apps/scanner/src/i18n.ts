export type ScannerKey = Key;

export function tr(lang: Lang) {
  const dict = lang === "am" ? am : en;
  return (key: Key, vars?: Record<string, string | number>) =>
    dict[key].replace(/\{(\w+)\}/g, (_, k: string) => String(vars?.[k] ?? ""));
}
